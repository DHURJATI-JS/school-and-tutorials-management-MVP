"""Application settings, loaded from the project's .env file (see .env.example)."""
from __future__ import annotations

import re
from pathlib import Path
from urllib.parse import quote_plus
from zoneinfo import ZoneInfo

from pydantic_settings import BaseSettings, SettingsConfigDict

APP_DIR = Path(__file__).resolve().parent
BASE_DIR = APP_DIR.parent
WEEKDAYS = ["mon", "tue", "wed", "thu", "fri", "sat", "sun"]


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=str(BASE_DIR / ".env"), env_file_encoding="utf-8", extra="ignore"
    )

    # ---- Application --------------------------------------------------------
    APP_NAME: str = "ClassNest"
    APP_TAGLINE: str = "AI-powered classrooms for small schools & tuition centres"
    APP_ENV: str = "development"
    DEBUG: bool = False
    SECRET_KEY: str = "insecure-dev-key-change-me"
    BASE_URL: str = "http://localhost:8080"
    HOST: str = "0.0.0.0"
    PORT: int = 8080
    SSL_CERTFILE: str = ""
    SSL_KEYFILE: str = ""
    SESSION_COOKIE_SECURE: bool = False
    SESSION_MAX_AGE_HOURS: int = 12
    TRUST_PROXY_HEADERS: bool = False
    # Only when TRUST_PROXY_HEADERS=true: comma-separated IPs of YOUR reverse proxies. X-Forwarded-For is
    # honoured only from these hosts (the right-most untrusted address becomes the client IP).
    FORWARDED_ALLOW_IPS: str = "127.0.0.1"
    # How long an idle HTTP connection stays open between requests. Longer than the 30 s notification poll, so open
    # pages reuse their connection. uvicorn's 5 s default made busy servers reset connections as the next request
    # arrived (found by the load test).
    KEEP_ALIVE_SECONDS: int = 75
    TIMEZONE: str = "Asia/Kolkata"
    CURRENCY_SYMBOL: str = "₹"
    IN_DOCKER: bool = False

    # ---- Admins: JSON dict {"username": "password-or-bcrypt-hash"} ------------
    ADMIN_USERS: dict[str, str] = {}
    ADMIN_ALERT_EMAILS: str = ""

    # ---- PostgreSQL + pgvector ----------------------------------------------
    POSTGRES_HOST: str = "localhost"
    POSTGRES_PORT: int = 5432
    POSTGRES_DB: str = "classnest"
    POSTGRES_USER: str = "classnest"
    POSTGRES_PASSWORD: str = "classnest"
    DATABASE_URL: str = ""
    DB_POOL_SIZE: int = 15
    DB_MAX_OVERFLOW: int = 25
    DB_POOL_TIMEOUT_SECONDS: float = 30
    DB_ECHO: bool = False

    # ---- AI provider ---------------------------------------------------------------
    # auto      = local Gemma 3 on vLLM when run.py finds an NVIDIA/AMD GPU, else Claude if ANTHROPIC_API_KEY is
    #             set, else the OpenAI-compatible gateway below
    # local     = always the bundled vLLM container (run.py starts it and points OPENAI_BASE_URL at it)
    # openai    = the OpenAI-compatible gateway in OPENAI_BASE_URL (vLLM, Ollama, LM Studio, a LAN server...)
    # anthropic = Claude through the Anthropic API (needs ANTHROPIC_API_KEY)
    # off       = no AI; every feature uses its built-in fallback
    AI_PROVIDER: str = "auto"
    LOCAL_LLM_INFO: str = ""  # set by run.py when it links the app to the local vLLM container (display only)

    # ---- Claude (Anthropic API) -----------------------------------------------------
    ANTHROPIC_API_KEY: str = ""
    ANTHROPIC_MODEL: str = "claude-opus-5-5"  # or claude-sonnet-5-5 / claude-haiku-5-5 for lower cost
    ANTHROPIC_EFFORT: str = "medium"          # low | medium | high | xhigh | max (thinking depth -> cost/latency)
    ANTHROPIC_MAX_TOKENS: int = 16000         # thinking + answer; prompts keep the visible answers short
    ANTHROPIC_MAX_CONCURRENCY: int = 8

    # ---- AI: OpenAI-compatible endpoint - by default the bundled vLLM container (Gemma 3) -----------
    OPENAI_BASE_URL: str = "http://127.0.0.1:8002/v1"
    OPENAI_API_KEY: str = ""  # the vLLM container's key (generated by run.py, stored in .env)
    LLM_MODEL: str = "auto"
    LLM_FALLBACK_MODEL: str = "gemma"
    LLM_VISION: str = "auto"  # auto | true | false  (Gemma 3 can read images; auto-detected)
    LLM_TEMPERATURE: float = 0.4
    LLM_MAX_TOKENS: int = 2048
    LLM_TIMEOUT_SECONDS: float = 120
    LLM_MAX_RETRIES: int = 2
    AI_MAX_CONCURRENCY: int = 4
    AI_CIRCUIT_FAILURES: int = 3
    AI_CIRCUIT_COOLDOWN_SECONDS: int = 60
    EMBEDDING_MODEL: str = ""
    EMBEDDING_DIM: int = 768
    TRANSCRIBE_MODEL: str = ""

    # ---- OCR micro-service (Tesseract, Docker) ------------------------------
    OCR_SERVICE_URL: str = "http://localhost:8001"
    OCR_SHARED_SECRET: str = ""
    OCR_TIMEOUT_SECONDS: float = 60

    # ---- SMTP ----------------------------------------------------------------
    EMAIL_ENABLED: bool = True
    SMTP_HOST: str = "localhost"
    SMTP_PORT: int = 1025
    SMTP_USERNAME: str = ""
    SMTP_PASSWORD: str = ""
    SMTP_STARTTLS: bool = False
    SMTP_SSL: bool = False
    SMTP_FROM_EMAIL: str = "no-reply@classnest.local"
    SMTP_FROM_NAME: str = "ClassNest"
    SMTP_TIMEOUT_SECONDS: float = 20

    # ---- SMS (OTP to phone) ----------------------------------------------------
    SMS_PROVIDER: str = "console"  # console | twilio | webhook
    TWILIO_ACCOUNT_SID: str = ""
    TWILIO_AUTH_TOKEN: str = ""
    TWILIO_FROM_NUMBER: str = ""
    SMS_WEBHOOK_URL: str = ""
    SMS_WEBHOOK_TOKEN: str = ""
    DEFAULT_COUNTRY_CODE: str = "+91"

    # ---- Cashfree (optional): online fee payments + staff payouts ---------------
    CASHFREE_ENABLED: bool = False
    CASHFREE_ENV: str = "sandbox"  # sandbox | production
    CASHFREE_APP_ID: str = ""
    CASHFREE_SECRET_KEY: str = ""
    CASHFREE_API_VERSION: str = "2023-08-01"
    CASHFREE_PAYOUTS_ENABLED: bool = False
    CASHFREE_PAYOUT_CLIENT_ID: str = ""
    CASHFREE_PAYOUT_CLIENT_SECRET: str = ""
    CASHFREE_PAYOUT_API_VERSION: str = "2024-01-01"

    # ---- Public contact details (home page, e-mails, receipts, ban notices) - set your own in .env ----
    CONTACT_EMAIL: str = "contact@example.com"
    CONTACT_WHATSAPP: str = "+910000000000"
    CONTACT_PHONE: str = "+91 00000 00000"
    CONTACT_ADDRESS: str = "India"

    # ---- Academic rules ----------------------------------------------------------
    MAX_BATCHES: int = 12
    MIN_BATCH_MINUTES: int = 60
    MAX_DAILY_HOURS: float = 12
    WEEKLY_OFF_DAYS: str = "sun"
    VIDEO_ATTENDANCE_RATIO: float = 0.5
    MEETING_ATTENDANCE_RATIO: float = 0.9
    TEST_GRACE_SECONDS: int = 60

    # ---- Authentication ------------------------------------------------------------
    OTP_LENGTH: int = 6
    OTP_TTL_SECONDS: int = 300
    OTP_MAX_ATTEMPTS: int = 5
    OTP_RESEND_SECONDS: int = 60
    REQUIRE_OTP_FOR_PASSWORD_LOGIN: bool = False
    LOGIN_RATE_LIMIT: int = 10            # sign-in attempts per IP per 5 minutes
    ACCOUNT_LOCK_THRESHOLD: int = 10      # failed sign-ins per account (any IP) before a temporary lock
    ACCOUNT_LOCK_MINUTES: int = 15
    OTP_SENDS_PER_HOUR: int = 5           # sign-in codes e-mailed/texted to one person per hour
    OTP_FAILURES_PER_HOUR: int = 10       # wrong sign-in codes per person per hour (across resends)
    DELETED_RETENTION_DAYS: int = 30      # a deleted account stays dormant (restorable) this long, then is purged

    # ---- Chat moderation -------------------------------------------------------------
    ABUSE_MAX_STRIKES: int = 3
    ABUSE_WINDOW_HOURS: int = 24
    ABUSE_BAN_HOURS: int = 72
    EXTRA_BLOCKED_WORDS: str = ""
    CHAT_RATE_LIMIT: int = 12
    REPORTS_PER_HOUR: int = 5
    COMMENTS_PER_5_MIN: int = 10          # video comments + replies per person
    MAX_SOCKETS_PER_USER: int = 8         # simultaneous live connections per person, per feature

    # ---- Uploads ---------------------------------------------------------------------
    UPLOAD_DIR: str = "uploads"
    MAX_UPLOAD_MB: int = 15
    MAX_VIDEO_MB: int = 2048
    MAX_FORM_MB: int = 2                  # non-file request bodies (forms, JSON); admin pages get 8 MB

    # ---- WebRTC (live classes) ----------------------------------------------------------
    STUN_URLS: str = "stun:stun.l.google.com:19302"
    TURN_URL: str = ""
    TURN_USERNAME: str = ""
    TURN_CREDENTIAL: str = ""

    # ---- Background jobs -------------------------------------------------------------------
    JOBS_ENABLED: bool = True
    JOBS_INTERVAL_SECONDS: int = 300
    PERFORMANCE_CHECK_HOURS: int = 24
    NOTIFY_PARENTS: bool = True

    # ---- Front-end assets ----------------------------------------------------------------------
    MINIFY_ASSETS: bool = True

    # ---- Derived values ----------------------------------------------------------------------
    @property
    def ai_provider(self) -> str:
        """The backend the app uses: 'openai' (local vLLM or a gateway), 'anthropic' or 'off'.
        run.py resolves 'auto'/'local' first when it starts a local model (it exports AI_PROVIDER=openai)."""
        choice = self.AI_PROVIDER.strip().lower()
        if choice in ("anthropic", "claude"):
            return "anthropic"
        if choice in ("off", "none", "disabled"):
            return "off"
        if choice == "auto" and self.ANTHROPIC_API_KEY.strip() and not self.LOCAL_LLM_INFO:
            return "anthropic"
        return "openai"

    @property
    def database_url(self) -> str:
        if self.DATABASE_URL:
            return self.DATABASE_URL
        user, pwd = quote_plus(self.POSTGRES_USER), quote_plus(self.POSTGRES_PASSWORD)
        return f"postgresql+asyncpg://{user}:{pwd}@{self.POSTGRES_HOST}:{self.POSTGRES_PORT}/{self.POSTGRES_DB}"

    @property
    def smtp_host(self) -> str:
        host = self.SMTP_HOST.strip()
        # Inside docker-compose "localhost" means the container itself: use the Mailpit service.
        if self.IN_DOCKER and host in {"localhost", "127.0.0.1"}:
            return "mailpit"
        return host

    @property
    def tz(self) -> ZoneInfo:
        return ZoneInfo(self.TIMEZONE)

    @property
    def weekly_off(self) -> set[int]:
        days = set()
        for part in self.WEEKLY_OFF_DAYS.split(","):
            key = part.strip()[:3].lower()
            if key in WEEKDAYS:
                days.add(WEEKDAYS.index(key))
        return days

    @property
    def admin_alert_list(self) -> list[str]:
        emails = [e.strip() for e in self.ADMIN_ALERT_EMAILS.split(",") if e.strip()]
        return emails or [self.CONTACT_EMAIL]

    @property
    def upload_root(self) -> Path:
        path = Path(self.UPLOAD_DIR)
        return path if path.is_absolute() else BASE_DIR / path

    @property
    def ice_servers(self) -> list[dict]:
        servers: list[dict] = []
        stun = [u.strip() for u in self.STUN_URLS.split(",") if u.strip()]
        if stun:
            servers.append({"urls": stun})
        if self.TURN_URL:
            servers.append(
                {"urls": [self.TURN_URL], "username": self.TURN_USERNAME, "credential": self.TURN_CREDENTIAL}
            )
        return servers

    @property
    def whatsapp_link(self) -> str:
        return "https://wa.me/" + re.sub(r"\D", "", self.CONTACT_WHATSAPP)

    @property
    def is_production(self) -> bool:
        return self.APP_ENV.lower() in {"prod", "production"}

    @property
    def cashfree_pg_active(self) -> bool:
        return bool(self.CASHFREE_ENABLED and self.CASHFREE_APP_ID and self.CASHFREE_SECRET_KEY)

    @property
    def cashfree_payouts_active(self) -> bool:
        return bool(self.CASHFREE_PAYOUTS_ENABLED and self.CASHFREE_PAYOUT_CLIENT_ID
                    and self.CASHFREE_PAYOUT_CLIENT_SECRET)


settings = Settings()
